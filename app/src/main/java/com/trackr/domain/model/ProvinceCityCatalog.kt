    /**
     * 剥离行政区划后缀，提取城市核心名称
     */
    fun cleanCityName(raw: String): String {
        var s = raw.trim()
        val suffixes = listOf(
            "特别行政区",
            "壮族自治区",
            "维吾尔自治区",
            "回族自治区",
            "藏族羌族自治州",
            "土家族苗族自治州",
            "朝鲜族自治州",
            "哈萨克自治州",
            "傣族自治州",
            "白族自治州",
            "藏族自治州",
            "蒙古自治州",
            "自治州",
            "自治区",
            "地区",
            "新区",
            "盟",
            "市",
            "县",
            "区",
            "省"
        )
        for (suffix in suffixes) {
            if (s.endsWith(suffix) && s.length > suffix.length) {
                s = s.removeSuffix(suffix)
                break
            }
        }
        return s.trim()
    }

    /**
     * 根据城市名推断所属省份或直辖市
     */
