        val clean = cleanCityName(cityName)
        if (clean.isBlank()) return "其他"

        // 1. 直辖市检查
        if (clean in listOf("北京", "上海", "天津", "重庆")) {
            return "直辖市"
        }

        // 2. 查表直接命中
        CITY_TO_PROVINCE[clean]?.let { return it }

        // 3. 包含匹配（如 "新疆乌鲁木齐" 或 "苏州市"）
        for ((city, prov) in CITY_TO_PROVINCE) {
            if (clean == city || clean.startsWith(city) || city.startsWith(clean)) {
                return prov
            }
        }

        // 4. 输入文本中直接包含省份全称或简称
        for (prov in PROVINCE_ORDER) {
            if (prov != "其他" && prov != "直辖市" && cityName.contains(prov)) {
                return prov
            }
        }

        return "其他"
    }

    /**
     * 判断是否为本目录收录的已知城市
     */
    fun isKnownCity(cityName: String): Boolean {
        val clean = cleanCityName(cityName)
        if (clean.isBlank()) return false
        return CITY_TO_PROVINCE.containsKey(clean) || inferProvince(clean) != "其他"
    }

    /**
     * 获取城市中心的标准 WGS-84 经纬度坐标，未收录时默认返回上海市中心人民广场
     */
    fun getCityCenterCoordinates(cityName: String): Pair<Double, Double> {
        val clean = cleanCityName(cityName)
        CITY_COORDINATES[clean]?.let { return it }

        for ((city, coords) in CITY_COORDINATES) {
            if (clean.contains(city) || city.contains(clean)) {
                return coords
            }
        }
        return Pair(31.2304, 121.4737)
    }

    /**
     * 计算两点间的 WGS-84 大圆距离（米）
     */
    fun haversineMeters(lat1: Double, lon1: Double, lat2: Double, lon2: Double): Double {
        val r = 6371000.0 // 地球平均半径（米）
        val dLat = Math.toRadians(lat2 - lat1)
        val dLon = Math.toRadians(lon2 - lon1)
        val lat1Rad = Math.toRadians(lat1)
        val lat2Rad = Math.toRadians(lat2)

        val a = sin(dLat / 2.0).let { it * it } +
                cos(lat1Rad) * cos(lat2Rad) *
                sin(dLon / 2.0).let { it * it }
        val c = 2.0 * atan2(sqrt(a), sqrt(1.0 - a))
        return r * c
    }

    /**
     * 在离线核心城市坐标表中寻找 80km 以内最近的城市名，作为网络定位异常时的兜底手段
     */
    fun findNearestCityName(wgsLat: Double, wgsLng: Double): String? {
        if (wgsLat == 0.0 && wgsLng == 0.0) return null
        var minDistance = Double.MAX_VALUE
        var nearestCity: String? = null
        val maxRadiusMeters = 80_000.0 // 80km

        for ((city, coords) in CITY_COORDINATES) {
            val dist = haversineMeters(wgsLat, wgsLng, coords.first, coords.second)
            if (dist < minDistance) {
                minDistance = dist
                nearestCity = city
            }
        }

        return if (minDistance <= maxRadiusMeters) nearestCity else null
    }
